// Tests of the early start of RunRanged (docs/SITE-MEDIA-SPEC.md §2.4): the other chunks
// may start once the received prefix of a track's first chunk passes its init check;
// every refusal is still decided on the complete first chunk.

// earlyProgressive returns a faststart progressive MP4 (ftyp, moov, mdat) with an H.264
// video track and an AAC track generated by internal/testmedia, of about 3 MiB.
func earlyProgressive(t *testing.T) []byte {
	t.Helper()
	v := testmedia.VideoConfig{Frames: 600, SliceBytes: 5000, Seed: 31}
	a := testmedia.AudioConfig{Frames: 940, Seed: 32}
	data, err := testmedia.ProgressiveMP4(v, testmedia.Video(v), a, testmedia.AAC(a))
	if err != nil {
		t.Fatal(err)
	}
	if len(data) < 2*media.MinChunkBytes {
		t.Fatalf("the fixture has %d bytes, want several chunks", len(data))
	}
	return data
}

// earlyRange parses the "bytes=a-b" of a request.
func earlyRange(r *http.Request) (a, b int64, ok bool) {
	spec, ok1 := strings.CutPrefix(r.Header.Get("Range"), "bytes=")
	first, last, ok2 := strings.Cut(spec, "-")
	a, err1 := strconv.ParseInt(first, 10, 64)
	b, err2 := strconv.ParseInt(last, 10, 64)
	return a, b, ok1 && ok2 && err1 == nil && err2 == nil
}

// earlyHeadRange reports whether the Range header v asks for bytes of a track's first
// chunk (of media.MinChunkBytes): from byte 0, or after a prefix the chunk kept.
func earlyHeadRange(v string) bool {
	spec, ok := strings.CutPrefix(v, "bytes=")
	first, _, ok2 := strings.Cut(spec, "-")
	a, err := strconv.ParseInt(first, 10, 64)
	return ok && ok2 && err == nil && a < media.MinChunkBytes
}

// earlyIsHead reports whether r asks for bytes of a track's first chunk.
func earlyIsHead(r *http.Request) bool { return earlyHeadRange(r.Header.Get("Range")) }

// earlyServeHead answers r, a request for the first chunk of data (from byte 0 or after
// a kept prefix), with a 206 of which it sends the bytes before offset prefix at once,
// then calls hold, then sends the rest unless the client went away. It returns true: the
// request is answered.
func earlyServeHead(w http.ResponseWriter, r *http.Request, data []byte, prefix int64, hold func()) bool {
	a, b, ok := earlyRange(r)
	if !ok || a >= media.MinChunkBytes {
		http.Error(w, "unexpected range", http.StatusBadRequest)
		return true
	}
	b = min(b, int64(len(data)-1))
	w.Header().Set("Content-Type", "video/mp4")
	w.Header().Set("Content-Range", fmt.Sprintf("bytes %d-%d/%d", a, b, len(data)))
	w.Header().Set("Content-Length", strconv.FormatInt(b-a+1, 10))
	w.WriteHeader(http.StatusPartialContent)
	cut := max(a, min(prefix, b+1))
	_, _ = w.Write(data[a:cut])
	w.(http.Flusher).Flush()
	hold()
	if r.Context().Err() == nil {
		_, _ = w.Write(data[cut : b+1])
	}
	return true
}

// earlyOther waits until s has seen a request that is not for a first chunk, at most
// limit or until r's client went away, and reports whether it came.
func earlyOther(s *siteServer, r *http.Request, limit time.Duration) bool {
	deadline := time.Now().Add(limit)
	for time.Now().Before(deadline) && r.Context().Err() == nil {
		for _, q := range s.requests("") {
			if !earlyHeadRange(q.rng) {
				return true
			}
		}
		time.Sleep(time.Millisecond)
	}
	return false
}

// earlyPause waits d or until r's client went away.
func earlyPause(r *http.Request, d time.Duration) {
	select {
	case <-time.After(d):
	case <-r.Context().Done():
	}
}

// earlyOthersBefore returns the requests s saw for other than a first chunk before t.
func earlyOthersBefore(s *siteServer, t time.Time) []string {
	var out []string
	for _, q := range s.requests("") {
		if !earlyHeadRange(q.rng) && q.at.Before(t) {
			out = append(out, q.path+" "+q.rng)
		}
	}
	return out
}

// earlyConcat is an Options.Assemble that writes the tracks' files one after the other.
func earlyConcat(ctx context.Context, inputs []remux.Input, out string) (string, error) {
	var b []byte
	for _, in := range inputs {
		for _, p := range in.Fragments {
			d, err := os.ReadFile(p)
			if err != nil {
				return "", err
			}
			b = append(b, d...)
		}
	}
	return "mp4", os.WriteFile(out, b, 0o600)
}

// earlyCopySelection selects the muxed MP4 at path of s, in 1 MiB chunks.
func earlyCopySelection(s *siteServer, path string, size int) RangedSelection {
	return RangedSelection{Output: OutputCopy, Tracks: []media.RangedTrack{
		rangedTrack("18", media.KindMuxed, "mp4", s.url(path), int64(size)),
	}}
}

// earlyEachChunkOnce checks that the requests for path were each chunk of a file of size
// bytes exactly once.
func earlyEachChunkOnce(t *testing.T, s *siteServer, path string, size int64) {
	t.Helper()
	got := rangesOf(s.requests(path))
	var want []string
	for i := range int((size + media.MinChunkBytes - 1) / media.MinChunkBytes) {
		want = append(want, path+" "+chunkRange(i, media.MinChunkBytes, size))
	}
	slices.Sort(got)
	slices.Sort(want)
	if !slices.Equal(got, want) {
		t.Errorf("%s: requests %v, want each chunk once: %v", path, got, want)
	}
}

// (a) A faststart MP4 that is copied: once the received prefix of the first chunk holds
// a complete 'moov' that passes the checks, the other chunks are requested while the
// first is still arriving, and the output is the served file.
func TestRunRangedEarlyStartCopy(t *testing.T) {
	data := earlyProgressive(t)
	s := newSiteServer(t)
	s.add("/18.mp4", data)
	var early atomic.Bool
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		if !earlyIsHead(r) {
			return false
		}
		return earlyServeHead(w, r, data, 256<<10, func() { early.Store(earlyOther(s, r, 10*time.Second)) })
	})
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	container, err := RunRanged(testContext(t), opts, earlyCopySelection(s, "/18.mp4", len(data)), nil, nil, nil)
	if err != nil || container != "mp4" {
		t.Fatalf("RunRanged = %q, %v", container, err)
	}
	if !early.Load() {
		t.Error("no other chunk was requested before the first chunk's last byte was sent")
	}
	if !bytes.Equal(readFile(t, opts.OutPath), data) {
		t.Fatal("the output differs from the served file")
	}
	earlyEachChunkOnce(t, s, "/18.mp4", int64(len(data)))
}

// (a) A fragmented MP4 pair that is joined: other chunks start once both first chunks'
// prefixes pass, and the output equals that of a run without the holds.
func TestRunRangedEarlyStartRemux(t *testing.T) {
	ref := newSiteServer(t)
	refSel, _, _ := pairSelection(t, ref, "/")
	refOpts := rangedOptions(t)
	if _, err := RunRanged(testContext(t), refOpts, refSel, nil, nil, nil); err != nil {
		t.Fatal(err)
	}

	s := newSiteServer(t)
	sel, v, a := pairSelection(t, s, "/")
	files := map[string][]byte{"/v.mp4": v.data, "/a.m4a": a.data}
	var held, early atomic.Int32
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		if !earlyIsHead(r) {
			return false
		}
		held.Add(1)
		return earlyServeHead(w, r, files[r.URL.Path], 64<<10, func() {
			if earlyOther(s, r, 10*time.Second) {
				early.Add(1)
			}
		})
	})
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	if _, err := RunRanged(testContext(t), opts, sel, nil, nil, nil); err != nil {
		t.Fatal(err)
	}
	if held.Load() != 2 || early.Load() != 2 {
		t.Errorf("%d of %d first chunks saw another request before their last byte, want both", early.Load(), held.Load())
	}
	checkMP4(t, opts.OutPath, v.samples, a.samples)
	if !bytes.Equal(readFile(t, opts.OutPath), readFile(t, refOpts.OutPath)) {
		t.Error("the output differs from a run without the early start")
	}
	earlyEachChunkOnce(t, s, "/v.mp4", int64(len(v.data)))
	earlyEachChunkOnce(t, s, "/a.m4a", int64(len(a.data)))
}

