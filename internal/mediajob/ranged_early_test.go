// (e) Once an early check started other chunks, a 200 to a retry of the first chunk is
// no longer taken as the whole track: it is retried after the prefix the chunk kept,
// and the output is byte-exact.
func TestRunRangedEarlyThenWholeIsRetried(t *testing.T) {
	data := earlyProgressive(t)
	s := newSiteServer(t)
	s.add("/18.mp4", data)
	var heads atomic.Int32
	var early atomic.Bool
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		if !earlyIsHead(r) {
			return false
		}
		switch heads.Add(1) {
		case 1: // a prefix that passes, then the connection breaks
			earlyServeHead(w, r, data, 256<<10, func() {
				early.Store(earlyOther(s, r, 10*time.Second))
				panic(http.ErrAbortHandler)
			})
			return true
		case 2: // the whole resource
			r.Header.Del("Range")
		}
		return false
	})
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	var rec recorder
	if _, err := RunRanged(testContext(t), opts, earlyCopySelection(s, "/18.mp4", len(data)), nil, nil, rec.onCheckpoint); err != nil {
		t.Fatal(err)
	}
	if !early.Load() {
		t.Fatal("the first attempt's prefix did not start the other chunks")
	}
	if !bytes.Equal(readFile(t, opts.OutPath), data) {
		t.Fatal("the output differs from the served file")
	}
	if n := heads.Load(); n != 3 {
		t.Errorf("%d requests for the first chunk, want 3 (broken, whole refused, ranged)", n)
	}
	rest := "bytes=" + strconv.Itoa(256<<10) + "-" + strconv.Itoa(media.MinChunkBytes-1)
	var firsts []string
	for _, q := range s.requests("") {
		if earlyHeadRange(q.rng) {
			firsts = append(firsts, q.rng)
		}
	}
	if len(firsts) != 3 || firsts[1] != rest || firsts[2] != rest {
		t.Errorf("first chunk requests %v, want the retries after the 256 KiB it kept", firsts)
	}
	n := (len(data) + media.MinChunkBytes - 1) / media.MinChunkBytes
	if cp := rec.last(); cp == nil || cp.Tracks[0].Total != n || cp.Tracks[0].ChunkBytes != media.MinChunkBytes {
		t.Errorf("checkpoint %+v, want %d ranged parts", rec.last(), n)
	}
}

// (f) A broken first attempt and a 403 during the first chunk renew the address; the
// first chunk continues after the bytes it kept, from the renewed address, where the
// early start works, and the run completes.
func TestRunRangedEarlyRefresh(t *testing.T) {
	data := earlyProgressive(t)
	s := newSiteServer(t)
	s.add("/old/18.mp4", data)
	s.add("/new/18.mp4", data)
	var early atomic.Bool
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		switch {
		case r.URL.Path == "/old/18.mp4" && n == 1: // a few bytes, then the connection breaks
			earlyServeHead(w, r, data, 100, func() { panic(http.ErrAbortHandler) })
			return true
		case r.URL.Path == "/old/18.mp4":
			w.WriteHeader(http.StatusForbidden)
			return true
		case r.URL.Path == "/new/18.mp4" && earlyIsHead(r):
			return earlyServeHead(w, r, data, 256<<10, func() { early.Store(earlyOther(s, r, 10*time.Second)) })
		}
		return false
	})
	sel := earlyCopySelection(s, "/old/18.mp4", len(data))
	var refreshes atomic.Int32
	sel.Refresh = func(context.Context) ([]media.RangedTrack, error) {
		refreshes.Add(1)
		return withURLs(sel, s, "/new/"), nil
	}
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	if _, err := RunRanged(testContext(t), opts, sel, nil, nil, nil); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(readFile(t, opts.OutPath), data) {
		t.Fatal("the output differs from the served file")
	}
	if n := refreshes.Load(); n != 1 {
		t.Errorf("%d renewals, want 1", n)
	}
	if !early.Load() {
		t.Error("the renewed first chunk's prefix did not start the other chunks")
	}
	kept := "bytes=100-" + strconv.Itoa(media.MinChunkBytes-1)
	if got := rangesOf(s.requests("/old/18.mp4")); !slices.Equal(got, []string{
		"/old/18.mp4 " + chunkRange(0, media.MinChunkBytes, 1<<40), "/old/18.mp4 " + kept,
	}) {
		t.Errorf("old address requests %v, want the first chunk, then its rest after 100 bytes", got)
	}
	got := rangesOf(s.requests("/new/18.mp4"))
	want := []string{"/new/18.mp4 " + kept}
	for i := 1; i < (len(data)+media.MinChunkBytes-1)/media.MinChunkBytes; i++ {
		want = append(want, "/new/18.mp4 "+chunkRange(i, media.MinChunkBytes, int64(len(data))))
	}
	slices.Sort(got)
	slices.Sort(want)
	if !slices.Equal(got, want) {
		t.Errorf("renewed address requests %v, want the rest of the first chunk and each other chunk once: %v", got, want)
	}
}

// (g) A resumed track whose first chunk is durable is checked from the file and has no
// gate: its other chunks start at once, side by side.
func TestRunRangedEarlyResumeWithFirstChunk(t *testing.T) {
	data := earlyProgressive(t)
	s := newSiteServer(t)
	s.add("/18.mp4", data)
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	sel := earlyCopySelection(s, "/18.mp4", len(data))

	ctx, cancel := context.WithCancel(testContext(t))
	defer cancel()
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		if earlyIsHead(r) {
			return false
		}
		<-r.Context().Done() // the other chunks never arrive
		return true
	})
	first := opts
	first.CheckpointInterval = 20 * time.Millisecond
	var rec syncRecorder
	onCheckpoint := func(cp Checkpoint) error {
		if bitSet(cp.Tracks[0].Done, 0) {
			cancel()
		}
		return rec.onCheckpoint(cp)
	}
	if _, err := RunRanged(ctx, first, sel, nil, nil, onCheckpoint); !errors.Is(err, context.Canceled) {
		t.Fatalf("interrupted run = %v, want context.Canceled", err)
	}
	cps := rec.all()
	cp := cps[len(cps)-1]
	if !bitSet(cp.Tracks[0].Done, 0) || bitSet(cp.Tracks[0].Done, 1) {
		t.Fatalf("checkpoint %+v, want only the first chunk durable", cp.Tracks[0])
	}

	resumed := newSiteServer(t)
	resumed.add("/18.mp4", data)
	resumed.setIntercept(func(w http.ResponseWriter, r *http.Request, n int) bool {
		earlyPause(r, 150*time.Millisecond)
		return false
	})
	sel = earlyCopySelection(resumed, "/18.mp4", len(data))
	if _, err := RunRanged(testContext(t), opts, sel, &cp, nil, nil); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(readFile(t, opts.OutPath), data) {
		t.Fatal("the resumed output differs from the served file")
	}
	reqs := resumed.requests("")
	if slices.ContainsFunc(reqs, func(q siteReq) bool { return strings.HasPrefix(q.rng, "bytes=0-") }) {
		t.Errorf("resumed requests %v ask for the durable first chunk again", rangesOf(reqs))
	}
	if want := cp.Tracks[0].Total - 1; len(reqs) != want || resumed.maxActive() != want {
		t.Errorf("%d resumed requests, %d at once; want %d, all at once", len(reqs), resumed.maxActive(), want)
	}
}

// (h) A run stopped while its first chunk arrives (after the early start let the
// others finish) never records that chunk as durable, only the prefix it received; the
// resumed run fetches the rest of it, alone, and the output is byte-exact.
func TestRunRangedEarlyKilledDuringFirstChunk(t *testing.T) {
	data := earlyProgressive(t)
	s := newSiteServer(t)
	s.add("/18.mp4", data)
	opts := rangedOptions(t)
	opts.MaxConnections = 8
	sel := earlyCopySelection(s, "/18.mp4", len(data))
	n := (len(data) + media.MinChunkBytes - 1) / media.MinChunkBytes

	ctx, cancel := context.WithCancel(testContext(t))
	defer cancel()
	s.setIntercept(func(w http.ResponseWriter, r *http.Request, _ int) bool {
		if !earlyIsHead(r) {
			return false
		}
		return earlyServeHead(w, r, data, 256<<10, func() { <-r.Context().Done() })
	})
	first := opts
	first.CheckpointInterval = 20 * time.Millisecond
	var mu sync.Mutex
	var cps []Checkpoint
	onCheckpoint := func(cp Checkpoint) error {
		mu.Lock()
		cps = append(cps, cp)
		mu.Unlock()
		all := true
		for i := 1; i < n; i++ {
			all = all && bitSet(cp.Tracks[0].Done, i)
		}
		if all {
			cancel()
		}
		return nil
	}
	if _, err := RunRanged(ctx, first, sel, nil, nil, onCheckpoint); !errors.Is(err, context.Canceled) {
		t.Fatalf("interrupted run = %v, want context.Canceled", err)
	}
	mu.Lock()
	defer mu.Unlock()
	for _, c := range cps {
		if bitSet(c.Tracks[0].Done, 0) {
			t.Fatalf("checkpoint %v marks the first chunk durable before it arrived", c.Tracks[0].Done)
		}
	}
	last := cps[len(cps)-1]
	for i := 1; i < n; i++ {
		if !bitSet(last.Tracks[0].Done, i) {
			t.Fatalf("checkpoint %v: chunk %d not durable", last.Tracks[0].Done, i)
		}
	}
	if p := last.Tracks[0].Partial; len(p) != 1 || p[0] != 256<<10 {
		t.Fatalf("checkpoint prefixes %v, want the 256 KiB of the first chunk", p)
	}

	resumed := newSiteServer(t)
	resumed.add("/18.mp4", data)
	sel = earlyCopySelection(resumed, "/18.mp4", len(data))
	if _, err := RunRanged(testContext(t), opts, sel, &last, nil, nil); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(readFile(t, opts.OutPath), data) {
		t.Fatal("the resumed output differs from the served file")
	}
	rest := "/18.mp4 bytes=" + strconv.Itoa(256<<10) + "-" + strconv.Itoa(media.MinChunkBytes-1)
	if got := rangesOf(resumed.requests("")); !slices.Equal(got, []string{rest}) {
		t.Errorf("resumed requests %v, want only the rest of the first chunk", got)
	}
}
