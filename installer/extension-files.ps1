# Writes the NSIS function IsShippedExtensionFile for installer\downex.nsi, which runs this
# script through !system while it compiles Setup.
#
#   extension-files.ps1 <SRCDIR\extension> <output .nsh>
#
# Setup overwrites the unpacked extension folders in place (a browser has them loaded, and a
# folder that disappears for a moment can make it disable the extension) and then deletes
# only the files this Setup does not ship. The function gets a file's path relative to
# $INSTDIR\extension in $1 and returns 1 in $2 when the file is one of the chrome-mv3 and
# firefox-mv3 files packed into Setup, 0 when it is not. StrCmp compares without case, as
# Windows file names do.
#
# Only .NET calls and the language itself: a cmdlet outside the core (Get-ChildItem,
# Join-Path, New-Object...) makes Windows PowerShell load its module first, and that load
# has been seen to crash powershell.exe now and then when makensis starts it.

param(
    [Parameter(Mandatory = $true)][string]$Source,
    [Parameter(Mandatory = $true)][string]$Out
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$base = [IO.Path]::GetFullPath($Source).TrimEnd('\')
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('; Generated by installer\extension-files.ps1 while makensis compiles downex.nsi.')
$lines.Add('Function IsShippedExtensionFile')
$lines.Add('  StrCpy $2 1')
$count = 0
foreach ($target in 'chrome-mv3', 'firefox-mv3') {
    $dir = [IO.Path]::Combine($base, $target)
    if (-not [IO.Directory]::Exists($dir)) { throw "$dir is missing" }
    # All files, hidden ones included: File /r packs those too.
    $files = [IO.Directory]::GetFiles($dir, '*', [IO.SearchOption]::AllDirectories)
    [Array]::Sort($files, [StringComparer]::OrdinalIgnoreCase)
    foreach ($f in $files) {
        $rel = $f.Substring($base.Length + 1)
        # A quote or a line break would end the NSIS string; $ is NSIS's variable sign.
        if ($rel -match '["`\r\n]') { throw "the extension has a file name Setup cannot list: $rel" }
        $lines.Add('  StrCmp $1 "' + $rel.Replace('$', '$$') + '" shipped')
        $count++
    }
}
if ($count -eq 0) { throw "no extension files in $base" }
$lines.Add('  StrCpy $2 0')
$lines.Add('  shipped:')
$lines.Add('FunctionEnd')
# UTF-8 with a byte order mark, which makensis reads whatever its /INPUTCHARSET.
[IO.File]::WriteAllLines($Out, $lines, [Text.UTF8Encoding]::new($true))
